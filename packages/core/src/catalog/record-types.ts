const byId = new Map<number, string>(RECORD_TYPES.map(([id, name]) => [id, name] as const));
const byName = new Map<string, number>(RECORD_TYPES.map(([id, name]) => [name.toLowerCase(), id] as const));

/** Legacy / alternate names Microsoft still emits in some exports and the PowerShell enum. */
const ALIASES: Record<string, string> = {
  'viva engage': 'Yammer',
  'vivaengage': 'Yammer',
  'workplaceanalytics': 'VivaInsights',
  'vivainsights (formerly workplaceanalytics)': 'VivaInsights',
  'viva goals': 'VivaGoals',
};

export function recordTypeName(id: number): string {
  return byId.get(id) ?? `RecordType ${id}`;
}

export function recordTypeId(name: string): number | null {
  const k = name.trim().toLowerCase();
  const alias = ALIASES[k];
  return byName.get(alias ? alias.toLowerCase() : k) ?? null;
}

/** Accepts a number, numeric string or enum name and returns both forms when known. */
export function resolveRecordType(v: unknown): { id: number | null; name: string | null } {
  if (v == null || v === '') return { id: null, name: null };
  if (typeof v === 'number') return { id: v, name: byId.get(v) ?? null };
  const s = String(v).trim();
  if (/^\d+$/.test(s)) { const id = +s; return { id, name: byId.get(id) ?? null }; }
  const id = recordTypeId(s);
  return { id, name: id != null ? byId.get(id)! : s };
}
